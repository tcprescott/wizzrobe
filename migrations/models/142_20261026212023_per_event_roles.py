"""Per-event roles: a grant of an on-site role names the event it's held in.

Phase 4 of the events restructure. ``userrole`` and ``discordrolemapping`` gain
a nullable ``event_id``: NULL for Staff and the online admin roles (and
SUPER_ADMIN), the event for Proctor, Broadcast Tech, Triforce Submitter,
Volunteer Coordinator, Equipment Manager, Volunteer and Check-in Desk.

1. **Columns** (generated).
2. **Backfill.** Every existing grant and Discord mapping of a per-event role
   moves into its community's default event, which is where all of them were
   used until now. Community-wide roles stay NULL.
3. **Uniques.** The old (user, role, tenant) unique is found by its columns and
   dropped, since its name differs between databases. Its replacement is two
   indexes: (user, role, tenant, event) for per-event rows, and a partial one on
   (user, role, tenant) WHERE event_id IS NULL, because Postgres treats NULLs
   as distinct and the first would let a community-wide role be granted twice.
   The Discord mapping key gets the same pair.
"""

from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True

_PER_EVENT = (
    'proctor', 'stream_manager', 'triforce_submitter', 'volunteer_coordinator',
    'equipment_manager', 'volunteer', 'check_in_desk',
)
_IN = ', '.join(f"'{r}'" for r in _PER_EVENT)


def _drop_unique(table: str, columns: tuple) -> str:
    cols = ', '.join(f"'{c}'" for c in columns)
    return f"""
        DO $$
        DECLARE r record;
        BEGIN
            FOR r IN
                SELECT i.relname AS idx, c.conname
                FROM pg_index x
                JOIN pg_class i ON i.oid = x.indexrelid
                JOIN pg_class t ON t.oid = x.indrelid
                LEFT JOIN pg_constraint c ON c.conindid = x.indexrelid AND c.contype = 'u'
                WHERE t.relname = '{table}' AND x.indisunique AND NOT x.indisprimary
                  AND (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                       FROM pg_attribute a
                       WHERE a.attrelid = t.oid AND a.attnum = ANY(x.indkey)) = ARRAY[{cols}]
            LOOP
                IF r.conname IS NOT NULL THEN
                    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', '{table}', r.conname);
                ELSE
                    EXECUTE format('DROP INDEX %I', r.idx);
                END IF;
            END LOOP;
        END $$;"""


async def upgrade(db: BaseDBAsyncClient) -> str:
    return '\n'.join([
        _drop_unique('userrole', ('role', 'tenant_id', 'user_id')),
        _drop_unique('discordrolemapping', ('app_role', 'discord_role_id', 'tenant_id')),
        """
        ALTER TABLE "discordrolemapping" ADD "event_id" INT;
        ALTER TABLE "userrole" ADD "event_id" INT;
        ALTER TABLE "discordrolemapping" ADD CONSTRAINT "fk_discordr_event_64c45a13" FOREIGN KEY ("event_id") REFERENCES "event" ("id") ON DELETE CASCADE;
        ALTER TABLE "userrole" ADD CONSTRAINT "fk_userrole_event_4ff66c0c" FOREIGN KEY ("event_id") REFERENCES "event" ("id") ON DELETE CASCADE;""",
        f"""
        UPDATE "userrole" x SET "event_id" = e."id"
        FROM "event" e
        WHERE e."tenant_id" = x."tenant_id" AND e."is_default"
          AND x."role" IN ({_IN}) AND x."event_id" IS NULL;
        UPDATE "discordrolemapping" x SET "event_id" = e."id"
        FROM "event" e
        WHERE e."tenant_id" = x."tenant_id" AND e."is_default"
          AND x."app_role" IN ({_IN}) AND x."event_id" IS NULL;""",
        """
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_userrole_user_id_563271" ON "userrole" ("user_id", "role", "tenant_id", "event_id");
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_userrole_community" ON "userrole" ("user_id", "role", "tenant_id") WHERE "event_id" IS NULL;
        CREATE INDEX IF NOT EXISTS "idx_userrole_event" ON "userrole" ("event_id");
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_discordrole_tenant__25247b" ON "discordrolemapping" ("tenant_id", "discord_role_id", "app_role", "event_id");
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_discordrolemapping_community" ON "discordrolemapping" ("tenant_id", "discord_role_id", "app_role") WHERE "event_id" IS NULL AND "app_role" IS NOT NULL;""",
    ])


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP INDEX IF EXISTS "uid_discordrolemapping_community";
        DROP INDEX IF EXISTS "uid_discordrole_tenant__25247b";
        ALTER TABLE "discordrolemapping" DROP CONSTRAINT IF EXISTS "fk_discordr_event_64c45a13";
        DROP INDEX IF EXISTS "idx_userrole_event";
        DROP INDEX IF EXISTS "uid_userrole_community";
        DROP INDEX IF EXISTS "uid_userrole_user_id_563271";
        ALTER TABLE "userrole" DROP CONSTRAINT IF EXISTS "fk_userrole_event_4ff66c0c";
        DELETE FROM "userrole" a USING "userrole" b
        WHERE a."id" > b."id" AND a."user_id" = b."user_id" AND a."role" = b."role"
          AND a."tenant_id" IS NOT DISTINCT FROM b."tenant_id";
        DELETE FROM "discordrolemapping" a USING "discordrolemapping" b
        WHERE a."id" > b."id" AND a."tenant_id" = b."tenant_id"
          AND a."discord_role_id" = b."discord_role_id" AND a."app_role" = b."app_role";
        ALTER TABLE "userrole" DROP COLUMN "event_id";
        ALTER TABLE "discordrolemapping" DROP COLUMN "event_id";
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_userrole_user_id_0e8710" ON "userrole" ("user_id", "role", "tenant_id");
        CREATE UNIQUE INDEX IF NOT EXISTS "uid_discordrole_tenant__55a366" ON "discordrolemapping" ("tenant_id", "discord_role_id", "app_role");"""


