async def upgrade(db: BaseDBAsyncClient) -> str:
    # The telemetry summaries count distinct sessions per community. Through the
    # lone session_id index Postgres scanned all of a community's rows in
    # session order (12s at 1.5M rows); (tenant_id, session_id) answers it from
    # the index alone. The old name differs from aerich's generated one, so drop both.
    return """
        DROP INDEX IF EXISTS "idx_telemetryev_session_id";
        DROP INDEX IF EXISTS "idx_telemetryev_session_82f5c3";
        CREATE INDEX IF NOT EXISTS "idx_telemetryev_tenant__765964" ON "telemetryevent" ("tenant_id", "session_id");"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP INDEX IF EXISTS "idx_telemetryev_tenant__765964";
        CREATE INDEX IF NOT EXISTS "idx_telemetryev_session_id" ON "telemetryevent" ("session_id");"""


