"""Events: every event-owned row must name its event; uniques are per event.

Phase 1 of the events restructure. Every write path now stamps ``event_id``,
so the columns 133 added on event-owned tables become NOT NULL. In order:

1. **Backfill again.** Rows written between 133 and this deploy (by code that
   didn't stamp an event yet) take their parent's event, or their community's
   default event, exactly as 133 did. Only NULLs are touched.
2. **Testing matches leave the default event's floor.** 133 moved test
   tournaments and their matches into the Testing event, but stages belong to
   the default event, so a Testing match on a stage pointed across events.
   Those matches lose their stage, and their players' station, as the spec
   says. Played results are untouched.
3. **NOT NULL** on every event-owned ``event_id`` (generated).
4. **Per-event uniques.** Names (stages, stations, volunteer positions), the
   check-in venue, role rule keys and the one-per-person rows (accommodation,
   emergency contact, events-seen) are unique within an event, not the whole
   community, so next year's event can reuse this year's names. The old
   community-wide uniques are found by their columns and dropped, because two
   of them (stage, volunteer position) were created by hand under names Tortoise
   doesn't generate.
"""

