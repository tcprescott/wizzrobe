def _fill_from_default(table: str) -> str:
    return f"""
        UPDATE "{table}" x SET "event_id" = e."id"
        FROM "event" e
        WHERE e."tenant_id" = x."tenant_id" AND e."is_default" AND x."event_id" IS NULL;"""


def _drop_unique(table: str, columns: tuple) -> str:
    cols = ', '.join(f"'{c}'" for c in columns)
    return f"""
        DO $$
        DECLARE r record;
        BEGIN
            FOR r IN
                SELECT i.relname AS idx, c.conname
                FROM pg_index x
                JOIN pg_class i ON i.oid = x.indexrelid
                JOIN pg_class t ON t.oid = x.indrelid
                LEFT JOIN pg_constraint c ON c.conindid = x.indexrelid AND c.contype = 'u'
                WHERE t.relname = '{table}' AND x.indisunique AND NOT x.indisprimary
                  AND (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                       FROM pg_attribute a
                       WHERE a.attrelid = t.oid AND a.attnum = ANY(x.indkey)) = ARRAY[{cols}]
            LOOP
                IF r.conname IS NOT NULL THEN
                    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', '{table}', r.conname);
                ELSE
                    EXECUTE format('DROP INDEX %I', r.idx);
                END IF;
            END LOOP;
        END $$;"""


async def upgrade(db: BaseDBAsyncClient) -> str:
    stmts: list[str] = []

    # --- Step 1: backfill rows written since 133 ---------------------------
    stmts.append(_fill_from_default('tournament'))
    stmts.append("""
        UPDATE "match" m SET "event_id" = tr."event_id"
        FROM "tournament" tr
        WHERE tr."id" = m."tournament_id" AND m."event_id" IS NULL;""")
    stmts.append(_fill_from_default('match'))
    for table in _OWNED_DEFAULT:
        stmts.append(_fill_from_default(table))
    stmts.append("""
        UPDATE "volunteershift" s SET "event_id" = p."event_id"
        FROM "volunteerposition" p
        WHERE p."id" = s."position_id" AND s."event_id" IS NULL;""")
    stmts.append(_fill_from_default('volunteershift'))
    stmts.append("""
        UPDATE "discordrolerule" r SET "event_id" = tr."event_id"
        FROM "tournament" tr
        WHERE tr."id" = r."tournament_id" AND r."event_id" IS NULL;""")
    stmts.append(_fill_from_default('discordrolerule'))
    stmts.append("""
        UPDATE "discordscheduledevent" d SET "event_id" = m."event_id"
        FROM "match" m
        WHERE d."source_type" = 'match' AND m."id" = d."source_id"
          AND m."tenant_id" = d."tenant_id" AND d."event_id" IS NULL;""")
    stmts.append(_fill_from_default('discordscheduledevent'))
    for table in _TAGGED:
        stmts.append(_fill_from_default(table))

    # --- Step 2: matches on another event's stage --------------------------
    stmts.append("""
        UPDATE "matchplayers" mp SET "assigned_station" = NULL
        FROM "match" m, "stage" st
        WHERE mp."match_id" = m."id" AND st."id" = m."stage_id"
          AND st."event_id" <> m."event_id" AND mp."assigned_station" IS NOT NULL;""")
    stmts.append("""
        UPDATE "match" m SET "stage_id" = NULL
        FROM "stage" st
        WHERE st."id" = m."stage_id" AND st."event_id" <> m."event_id";""")

    # --- Step 3: NOT NULL ----------------------------------------------------
    stmts.append(_NOT_NULL)

    # --- Step 4: per-event uniques -------------------------------------------
    for table, columns in _OLD_UNIQUES:
        stmts.append(_drop_unique(table, columns))
    stmts.append(_UNIQUES)

    return '\n'.join(stmts)


