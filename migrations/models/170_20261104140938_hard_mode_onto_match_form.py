    # Hard mode moves onto the match form: each tournament with a harder preset
    # gets a hidden Yes/No question first on its form and a first seed rule
    # "every player answered Yes -> the harder preset"; open opt-ins become Yes answers.
    # A tournament whose rules already roll the harder preset was moved by hand and is skipped.
    # Staff's two-value override becomes the preset it named, then the harder preset field goes.
    return """
        WITH eligible AS (
            SELECT t."id", t."tenant_id", t."hard_preset_id" FROM "tournament" t
            WHERE t."hard_preset_id" IS NOT NULL
              AND NOT EXISTS (
                SELECT 1 FROM "matchformquestion" x WHERE x."tournament_id" = t."id" AND x."key" = 'hardmode'
              )
              AND NOT COALESCE(t."seed_rules", '[]'::jsonb) @> jsonb_build_array(
                jsonb_build_object('then', jsonb_build_object('preset', t."hard_preset_id"))
              )
        ), shifted AS (
            UPDATE "matchformquestion" q SET "position" = q."position" + 1
            FROM eligible e WHERE q."tournament_id" = e."id" RETURNING q."id"
        ), asked AS (
            INSERT INTO "matchformquestion"
                ("key", "position", "kind", "prompt", "help", "choices", "config", "who", "ask_on", "visibility",
                 "tenant_id", "tournament_id")
            SELECT 'hardmode', 0, 'yes_no', 'Play Hard mode?',
                   'Hard mode is only played when every player in the match says Yes.',
                   '[{"value": "yes", "label": "Yes", "preset": null}, {"value": "no", "label": "No", "preset": null}]'::jsonb,
                   '{}'::jsonb, 'each_player', 'every_match', 'never', e."tenant_id", e."id"
            FROM eligible e RETURNING "id", "tournament_id"
        ), ruled AS (
            UPDATE "tournament" t SET "seed_rules" = jsonb_build_array(jsonb_build_object(
                    'id', 'hardmd', 'name', 'Hard mode',
                    'when', '{"answer": [{"q": "hardmode", "who": "every", "is": ["yes"]}]}'::jsonb,
                    'then', jsonb_build_object('preset', e."hard_preset_id")
                )) || COALESCE(t."seed_rules", '[]'::jsonb)
            FROM eligible e WHERE t."id" = e."id" RETURNING t."id"
        )
        INSERT INTO "matchformanswer" ("value", "match_id", "question_id", "tenant_id", "user_id")
        SELECT '{"v": "yes"}'::jsonb, o."match_id", a."id", o."tenant_id", o."user_id"
        FROM "matchhardpresetoptin" o
        JOIN "match" m ON m."id" = o."match_id"
        JOIN asked a ON a."tournament_id" = m."tournament_id";
        ALTER TABLE "match" ADD "forced_preset_id" INT;
        UPDATE "match" m SET "forced_preset_id" = CASE m."preset_override"
                WHEN 'hard' THEN t."hard_preset_id" ELSE t."preset_id" END
        FROM "tournament" t
        WHERE t."id" = m."tournament_id" AND m."preset_override" IS NOT NULL;
        ALTER TABLE "match" DROP COLUMN "preset_override";
        ALTER TABLE "tournament" DROP CONSTRAINT IF EXISTS "fk_tourname_preset_532a62ee";
        ALTER TABLE "tournament" DROP COLUMN "hard_preset_id";
        DROP TABLE IF EXISTS "matchhardpresetoptin";
        ALTER TABLE "match" ADD CONSTRAINT "fk_match_preset_5e190387" FOREIGN KEY ("forced_preset_id") REFERENCES "preset" ("id") ON DELETE SET NULL;"""


