async def upgrade(db: BaseDBAsyncClient) -> str:
    return """
        COMMENT ON COLUMN "staff_request_dm"."kind" IS 'COMMUNITY_EVENT: community_event\nADA_REQUEST: ada_request\nJOIN_REQUEST: join_request\nRESCHEDULE_REQUEST: reschedule_request\nCOMMENTATOR_SIGNUP: commentator_signup\nTRACKER_SIGNUP: tracker_signup';
-- Crew signup and withdrawal notices split by role: keep each community's and
-- each person's choice by copying it to both halves.
INSERT INTO "notificationsetting" ("tenant_id", "notice", "recipient", "mode", "updated_at", "updated_by_id")
SELECT "tenant_id", n.new_key, "recipient", "mode", "updated_at", "updated_by_id"
FROM "notificationsetting"
JOIN (VALUES
    ('crew_signup', 'commentator_signup'), ('crew_signup', 'tracker_signup'),
    ('crew_withdrew', 'commentator_withdrew'), ('crew_withdrew', 'tracker_withdrew')
) AS n(old_key, new_key) ON "notice" = n.old_key
ON CONFLICT ("tenant_id", "notice", "recipient") DO NOTHING;
DELETE FROM "notificationsetting" WHERE "notice" IN ('crew_signup', 'crew_withdrew');
UPDATE "notificationpreference" p SET "overrides" = (
    SELECT COALESCE(jsonb_object_agg(k, v), '{}'::jsonb) FROM (
        SELECT key AS k, value AS v FROM jsonb_each(p."overrides")
        WHERE split_part(key, ':', 1) NOT IN ('crew_signup', 'crew_withdrew')
        UNION ALL
        SELECT replace(key, 'crew_', r.role || '_'), value
        FROM jsonb_each(p."overrides"), (VALUES ('commentator'), ('tracker')) AS r(role)
        WHERE split_part(key, ':', 1) IN ('crew_signup', 'crew_withdrew')
    ) AS merged
)
WHERE EXISTS (
    SELECT 1 FROM jsonb_object_keys(p."overrides") AS key
    WHERE split_part(key, ':', 1) IN ('crew_signup', 'crew_withdrew')
);"""


