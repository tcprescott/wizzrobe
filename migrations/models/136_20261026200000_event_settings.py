"""Events: the event settings move off the community and onto each event.

Phase 2 of the events restructure. Five settings were one value per community
in ``systemconfiguration`` and now belong to an event, in ``event.config``:
capacity (``max_concurrent_players``, ``max_concurrent_stages``), daily hours
(``tournament_hours_by_date``), station numbering (``station_format``) and the
volunteer reward tiers (``volunteer_comp_tiers``). Each of a community's events
takes the community's value, unless it already has its own. The event dates
(``event_start_date`` / ``event_end_date``) fill ``event.starts_on`` /
``ends_on`` where 133 left them blank. The community rows are then deleted,
so nothing reads a stale copy.

Downgrade writes the default event's values back as community rows.
"""

from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True

_CONFIG_KEYS = [
    'max_concurrent_players', 'max_concurrent_stages', 'tournament_hours_by_date',
    'station_format', 'volunteer_comp_tiers',
]
_DATE_KEYS = {'event_start_date': 'starts_on', 'event_end_date': 'ends_on'}


def _keys_sql(keys) -> str:
    return ', '.join(f"'{k}'" for k in keys)


async def upgrade(db: BaseDBAsyncClient) -> str:
    statements = [f"""
        UPDATE "event" e SET "config" = COALESCE(e."config", '{{}}'::jsonb) || jsonb_build_object(c."name", c."value")
        FROM "systemconfiguration" c
        WHERE c."tenant_id" = e."tenant_id" AND c."name" = '{key}' AND c."value" <> ''
          AND NOT (COALESCE(e."config", '{{}}'::jsonb) ? '{key}');
    """ for key in _CONFIG_KEYS]
    statements += [f"""
        UPDATE "event" e SET "{column}" = c."value"::date
        FROM "systemconfiguration" c
        WHERE c."tenant_id" = e."tenant_id" AND c."name" = '{key}' AND e."{column}" IS NULL
          AND c."value" ~ '^[0-9]{{4}}-[0-9]{{2}}-[0-9]{{2}}$';
    """ for key, column in _DATE_KEYS.items()]
    statements.append(f"""
        DELETE FROM "systemconfiguration" WHERE "name" IN ({_keys_sql(_CONFIG_KEYS + list(_DATE_KEYS))});
    """)
    return '\n'.join(statements)


async def downgrade(db: BaseDBAsyncClient) -> str:
    statements = [f"""
        INSERT INTO "systemconfiguration" ("name", "value", "tenant_id", "created_at", "updated_at")
        SELECT '{key}', e."config"->>'{key}', e."tenant_id", NOW(), NOW()
        FROM "event" e
        WHERE e."is_default" AND e."config" ? '{key}'
        ON CONFLICT DO NOTHING;
    """ for key in _CONFIG_KEYS]
    statements += [f"""
        INSERT INTO "systemconfiguration" ("name", "value", "tenant_id", "created_at", "updated_at")
        SELECT '{key}', e."{column}"::text, e."tenant_id", NOW(), NOW()
        FROM "event" e
        WHERE e."is_default" AND e."{column}" IS NOT NULL
        ON CONFLICT DO NOTHING;
    """ for key, column in _DATE_KEYS.items()]
    return '\n'.join(statements)


